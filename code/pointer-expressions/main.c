/*
 * 指针表达式演示 —— 对应《C和指针》第 5 章第 101-104 页
 *
 * 跑法: mingw32-make run
 * 看每个表达式的实际行为，验证书的说法
 *
 * 关键概念:
 *   - 右值 = 表达式的"值"（能赋给变量）
 *   - 左值 = 表达式的"位置"（能赋值的内存位置）
 *   - 间接访问 = *（解引用）= 通过地址找到那个内存位置
 */

#include <stdio.h>

/* 打印 cp 当前状态的辅助宏 */
#define SHOW(label) \
    printf("    cp=%p  *cp='%c'  cp-ch=%td  ch=[%c,%c,%c,%c]\n", \
           (void*)cp, *cp, cp - ch, \
           ch[0], ch[1], ch[2], ch[3])

int main(void) {
    char ch[] = {'a', 'b', 'c', 'd'};
    char *cp = ch;       /* cp 指向 ch[0]='a' */

    printf("=== 初始状态 ===\n");
    SHOW("init: cp = ch, 指向 'a'");
    printf("\n");

    /* ============================================
     * 第 1 组：理解"右值 vs 左值"
     * ============================================ */
    printf("=== 第 1 组：右值 vs 左值 ===\n");

    /* cp —— 右值是 cp 的值（地址），左值是 cp 这个变量本身 */
    printf("cp        : 右值=%p（左值=cp 变量本身）\n", (void*)cp);

    /* &cp —— 右值是 cp 变量自己的地址（指针的指针），左值非法 */
    printf("&cp       : 右值=%p（cp 变量的地址）\n", (void*)&cp);

    /* *cp —— 右值是 cp 指向位置的值，左值是那个位置 */
    printf("*cp       : 右值='%c'（=97），左值=ch[0] 这个位置\n", *cp);

    /* &*cp —— 这个等价于 &ch[0]，右值是 ch[0] 的地址 */
    printf("&*cp      : 右值=%p (= &ch[0])\n", (void*)&*cp);
    printf("\n");

    /* ============================================
     * 第 2 组：*cp + 1 vs *(cp + 1) —— 括号的作用
     * ============================================ */
    printf("=== 第 2 组：括号决定运算顺序 ===\n");

    /* *cp + 1: * 优先级高于 +，先解引用得 'a'(97)，再 +1 = 'b'(98) */
    printf("*cp + 1   : = '%c' (= *cp + 1 = 'a' + 1 = 'b') ← 解引用 *cp 再 +1\n", *cp + 1);

    /* *(cp + 1): 括号强制 +1 先做，cp+1 指向 ch[1]，再解引用 */
    printf("*(cp + 1) : = '%c' (= ch[1]) ← cp 移动 1 再解引用\n", *(cp + 1));

    /* *++cp: 先 ++cp（指针指向 ch[1]），再解引用 */
    /* *cp++: 先取 cp 当前值，cp 自增，再解引用旧值（这是经典难点） */
    printf("\n");

    /* ============================================
     * 第 3 组：*++cp vs *cp++ —— 经典难点
     * ============================================ */
    printf("=== 第 3 组：*++cp vs *cp++（重头戏） ===\n");

    /* 重置 cp */
    cp = ch;
    printf("重置 cp → ch[0]\n");
    SHOW("before *++cp");

    /* *++cp: 优先级 ++ 高于 *，但执行：
       (1) ++cp：cp 先自增，指向 ch[1]='b'
       (2) *cp：解引用新位置
       结果：返回值='b'，cp 现在指向 ch[1] */
    char v1 = *++cp;
    printf("\n*++cp     : 返回 '%c', cp 已指向 ch[1]\n", v1);
    SHOW("after *++cp");

    /* 重置 */
    cp = ch;
    printf("\n重置 cp → ch[0]\n");
    SHOW("before *cp++");

    /* *cp++: 后缀 ++ 优先级最高，但行为是：
       (1) 暂存 cp 当前值（指针副本）
       (2) cp 自增（指向 ch[1]）
       (3) 对副本解引用
       结果：返回值='a'（旧位置），cp 现在指向 ch[1] */
    char v2 = *cp++;
    printf("\n*cp++     : 返回 '%c'（旧位置的值）, cp 已指向 ch[1]\n", v2);
    SHOW("after *cp++");
    printf("  关键差异: *++cp 返回 'b'（新位置），*cp++ 返回 'a'（旧位置）\n");
    printf("\n");

    /* ============================================
     * 第 4 组：++*cp vs (*cp)++ —— 操作的对象不同
     * ============================================ */
    printf("=== 第 4 组：++*cp vs (*cp)++ ===\n");

    /* 重置 */
    cp = ch;
    ch[0] = 'a'; ch[1] = 'b'; ch[2] = 'c'; ch[3] = 'd';
    printf("重置 cp 和 ch\n");
    SHOW("before");

    /* ++*cp: 优先级 * 高于 ++，但执行：
       (1) *cp：解引用得 ch[0]='a'
       (2) ++：ch[0] 自增 'a' → 'b'
       结果：ch[0] 变了，cp 没动 */
    ch[0] = 'a';
    ++*cp;
    printf("\n++*cp     : ch[0]='a' → '%c'（自增了 ch[0]）\n", ch[0]);
    SHOW("after ++*cp: cp 没动，只是 ch[0] 变了");

    /* 重置 */
    ch[0] = 'a';
    printf("\n重置 ch[0]='a'\n");

    /* (*cp)++: 括号强制先解引用，再后缀++
       (1) *cp：解引用得 ch[0]='a'（旧值）
       (2) ++：ch[0] 自增 'a' → 'b'
       结果：ch[0] 变了（旧值 'a'，新值 'b'），表达式结果是旧值 */
    char v3 = (*cp)++;
    printf("\n(*cp)++   : 表达式返回值='%c'（旧值 'a'），ch[0] 变成 '%c'\n", v3, ch[0]);
    SHOW("after (*cp)++");
    printf("\n");

    /* ============================================
     * 第 5 组：++*++cp vs ++*cp++ —— 组合技
     * ============================================ */
    printf("=== 第 5 组：++*++cp vs ++*cp++ ===\n");

    /* 重置 */
    cp = ch;
    ch[0] = 'a'; ch[1] = 'b'; ch[2] = 'c'; ch[3] = 'd';
    printf("重置 cp=ch[0]\n");
    SHOW("before ++*++cp");

    /* ++*++cp: 自右向左结合
       (1) ++cp: cp 从 ch[0] → ch[1]
       (2) *cp: 取 ch[1]='b'
       (3) ++: ch[1] 自增 'b' → 'c'
       结果：ch[1] 变了，cp 指向 ch[1] */
    ++*++cp;
    printf("\n++*++cp   : cp 从 ch[0]→ch[1], ch[1] 从 'b' → '%c'\n", ch[1]);
    SHOW("after ++*++cp");

    /* 重置 */
    cp = ch;
    ch[0] = 'a'; ch[1] = 'b'; ch[2] = 'c'; ch[3] = 'd';
    printf("\n重置\n");
    SHOW("before ++*cp++");

    /* ++*cp++: 自右向左
       (1) cp++ (后缀): 暂存 cp 当前值（指向 ch[0]），cp 自增到 ch[1]
       (2) *cp (旧值): 取 ch[0]='a'
       (3) ++: ch[0] 自增 'a' → 'b'
       结果：ch[0] 变了，cp 指向 ch[1] */
    ++*cp++;
    printf("\n++*cp++   : cp 从 ch[0]→ch[1], ch[0] 从 'a' → '%c'\n", ch[0]);
    SHOW("after ++*cp++");
    printf("\n");

    /* ============================================
     * 最终状态对比
     * ============================================ */
    printf("=== 最终状态 ===\n");
    printf("ch = ['%c', '%c', '%c', '%c']\n", ch[0], ch[1], ch[2], ch[3]);

    return 0;
}